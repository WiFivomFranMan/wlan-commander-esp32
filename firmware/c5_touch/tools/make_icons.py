#!/usr/bin/env python3
"""Generate the launcher icons (112x112 ARGB8888) as components/wlc_apps/src/icons.c."""
from pathlib import Path
from PIL import Image, ImageDraw
import math

S = 112
ROOT = Path(__file__).resolve().parents[1]

def base(color):
    im = Image.new("RGBA", (S * 4, S * 4), (0, 0, 0, 0))   # draw 4x, downsample for smooth edges
    d = ImageDraw.Draw(im)
    d.rounded_rectangle((8, 8, S * 4 - 8, S * 4 - 8), radius=96, fill=color)
    return im, d

W = (255, 255, 255, 255)

def scan():          # Wi-Fi arcs
    im, d = base((30, 136, 229, 255))
    cx, cy = 224, 320
    for r in (70, 140, 210):
        d.arc((cx - r, cy - r, cx + r, cy + r), 225, 315, fill=W, width=34)
    d.ellipse((cx - 26, cy - 26, cx + 26, cy + 26), fill=W)
    return im

def clients():       # two people
    im, d = base((0, 150, 136, 255))
    for x, s in ((165, 1.0), (285, 0.85)):
        r = 46 * s
        d.ellipse((x - r, 150 - r, x + r, 150 + r), fill=W)
        d.rounded_rectangle((x - 80 * s, 215, x + 80 * s, 215 + 130 * s), radius=60, fill=W)
    return im

def passpoint():     # key
    im, d = base((142, 36, 170, 255))
    d.ellipse((90, 150, 230, 290), outline=W, width=36)
    d.rectangle((222, 202, 370, 238), fill=W)
    d.rectangle((300, 238, 330, 290), fill=W)
    d.rectangle((345, 238, 370, 275), fill=W)
    return im

def spectrum():      # trace over bars
    im, d = base((229, 57, 53, 255))
    for i, h in enumerate((60, 110, 230, 170, 90, 140, 70)):
        x = 80 + i * 44
        d.rectangle((x, 360 - h, x + 30, 360), fill=(255, 255, 255, 200))
    pts = [(70 + i * 8, 200 - 70 * math.exp(-((i - 18) / 6) ** 2) + 10 * math.sin(i)) for i in range(40)]
    d.line(pts, fill=W, width=14, joint="curve")
    return im

def sensor():        # Bluetooth rune
    im, d = base((96, 125, 139, 255))
    p = [(170, 150), (290, 270), (224, 336), (224, 112), (290, 178), (170, 298)]
    d.line(p, fill=W, width=30, joint="curve")
    return im

def airhorn():       # horn and emitted waves
    im, d = base((239, 108, 0, 255))
    d.polygon([(85, 190), (150, 190), (260, 115), (260, 325), (150, 250), (85, 250)], fill=W)
    d.rectangle((120, 245, 160, 325), fill=W)
    for r in (45, 90):
        d.arc((250-r, 220-r, 250+r, 220+r), -60, 60, fill=W, width=18)
    return im

def emit(name, im):
    im = im.resize((S, S), Image.LANCZOS)
    data = bytearray()
    for r, g, b, a in im.getdata():
        data += bytes((b, g, r, a))
    rows = ",\n".join("  " + ", ".join(f"0x{v:02x}" for v in data[i:i + 24]) for i in range(0, len(data), 24))
    return (f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{\n{rows}\n}};\n"
            f"const lv_image_dsc_t {name} = {{\n  .header = {{ .magic = LV_IMAGE_HEADER_MAGIC, "
            f".cf = LV_COLOR_FORMAT_ARGB8888, .w = {S}, .h = {S}, .stride = {S * 4} }},\n"
            f"  .data_size = sizeof({name}_map),\n  .data = {name}_map,\n}};\n\n")

out = ["// SPDX-License-Identifier: MIT\n// Generated by tools/make_icons.py. Do not edit.\n#include \"lvgl.h\"\n\n"]
for fn in (scan, clients, passpoint, spectrum, sensor, airhorn):
    out.append(emit(f"wlc_icon_{fn.__name__}", fn()))
(ROOT / "components/wlc_apps/src/icons.c").write_text("".join(out))
print("wrote icons.c")
