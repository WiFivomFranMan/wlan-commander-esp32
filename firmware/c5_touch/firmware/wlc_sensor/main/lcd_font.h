static inline uint8_t lcd_glyph(char c, unsigned column) {
 if (column >= 5) return 0;
 if (c >= 'a' && c <= 'z') c -= 32;
 if (c >= '0' && c <= '9') return LCD_FONT[c-'0'][column];
 if (c >= 'A' && c <= 'Z') return LCD_FONT[c-'A'+10][column];
 if (c == ':') return column == 2 ? 0x24 : 0;
 if (c == '.') return column == 2 ? 0x40 : 0;
 if (c == '/') return (uint8_t)(0x40 >> column);
 if (c == '-') return 8;
 if (c == '%') { const uint8_t p[5]={0x43,0x23,0x10,0x68,0x64}; return p[column]; }
 if (c == '(') return column == 2 ? 0x3e : column == 3 ? 0x41 : 0;
 if (c == ')') return column == 2 ? 0x41 : column == 3 ? 0x3e : 0;
 return 0;
}
